/** Stable block ids (data-id) on block-level nodes, used for citation anchors (#block-<id>). */
export const BlockId = Extension.create({
  name: "blockId",
  addGlobalAttributes() { return [{ types: ["paragraph", "heading", "blockquote", "codeBlock", "bulletList", "orderedList", "taskList", "table", "callout", "details", "aiBlock", "blockMath", "image", "fileBlock"], attributes: { id: { default: null, keepOnSplit: false, parseHTML: (el) => el.getAttribute("data-id"), renderHTML: (a) => (a.id ? { "data-id": a.id, id: `block-${a.id}` } : {}) } } }]; },
  addProseMirrorPlugins() {
    const types = new Set(["paragraph", "heading", "blockquote", "codeBlock", "bulletList", "orderedList", "taskList", "table", "callout", "details", "aiBlock", "blockMath", "image", "fileBlock"]);
    return [new Plugin({ key: new PluginKey("blockId"), appendTransaction: (trs, _old, state) => {
      if (!trs.some((t) => t.docChanged)) return null; const seen = new Set<string>(); let tr = state.tr; let mod = false;
      state.doc.descendants((node, pos) => { if (!types.has(node.type.name)) return; const id = node.attrs.id; if (!id || seen.has(id)) { tr = tr.setNodeMarkup(pos, undefined, { ...node.attrs, id: nanoid(10) }); mod = true; } else seen.add(id); });
      return mod ? tr : null;
    } })];
  },
});
