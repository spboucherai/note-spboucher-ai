import { Node, mergeAttributes, Extension } from "@tiptap/core";
import { Plugin, PluginKey } from "@tiptap/pm/state";
import { nanoid } from "nanoid";

/** Callout block: kind = note|info|warning|danger|ai, icon = emoji. */
export const Callout = Node.create({
  name: "callout", group: "block", content: "block+", defining: true,
  addAttributes() { return { kind: { default: "note", parseHTML: (el) => el.getAttribute("data-kind") ?? "note", renderHTML: (a) => ({ "data-kind": a.kind }) }, icon: { default: "💡", parseHTML: (el) => el.getAttribute("data-icon") ?? "💡", renderHTML: (a) => ({ "data-icon": a.icon }) } }; },
  parseHTML() { return [{ tag: "div.callout" }]; },
  renderHTML({ HTMLAttributes, node }) { return ["div", mergeAttributes(HTMLAttributes, { class: "callout" }), ["span", { class: "callout-icon", contenteditable: "false" }, node.attrs.icon], ["div", { class: "callout-body flex-1 min-w-0" }, 0]]; },
  addCommands() { return { setCallout: (attrs: { kind?: string; icon?: string } = {}) => ({ commands }: any) => commands.wrapIn(this.name, attrs), toggleCallout: (attrs: { kind?: string; icon?: string } = {}) => ({ commands }: any) => commands.toggleWrap(this.name, attrs) } as any; },
});
/** AI-generated content block: keeps provenance (model, prompt) around the generated blocks. */
export const AIBlock = Node.create({
  name: "aiBlock", group: "block", content: "block+", defining: true,
  addAttributes() { return { model: { default: null, parseHTML: (el) => el.getAttribute("data-model"), renderHTML: (a) => ({ "data-model": a.model }) }, prompt: { default: null, parseHTML: (el) => el.getAttribute("data-prompt"), renderHTML: (a) => ({ "data-prompt": a.prompt }) }, at: { default: null, parseHTML: (el) => el.getAttribute("data-at"), renderHTML: (a) => ({ "data-at": a.at }) } }; },
  parseHTML() { return [{ tag: "div.ai-block" }]; },
  renderHTML({ HTMLAttributes }) { return ["div", mergeAttributes(HTMLAttributes, { class: "ai-block", title: `Generated by ${HTMLAttributes["data-model"] ?? "AI"}` }), 0]; },
});
/** File attachment block (atom). */
export const FileBlock = Node.create({
  name: "fileBlock", group: "block", atom: true, draggable: true,
  addAttributes() { return { src: { default: null }, name: { default: "file" }, size: { default: 0 }, mime: { default: "" }, attachmentId: { default: null } }; },
  parseHTML() { return [{ tag: "a.file-block" }]; },
  renderHTML({ HTMLAttributes, node }) { const kb = node.attrs.size ? `${(node.attrs.size / 1024).toFixed(0)} KB` : ""; return ["a", mergeAttributes({ class: "file-block", href: node.attrs.src, target: "_blank", rel: "noopener", "data-attachment-id": node.attrs.attachmentId, "data-name": node.attrs.name, "data-size": node.attrs.size, "data-mime": node.attrs.mime }), ["span", { class: "text-lg" }, "📎"], ["span", { class: "flex-1 min-w-0 truncate text-sm font-medium" }, node.attrs.name], ["span", { class: "text-xs text-fg-faint" }, kb]]; },
});
